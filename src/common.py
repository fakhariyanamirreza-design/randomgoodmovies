def country_names_fa(details):
    """اسامی فارسی کشورهای سازنده از آبجکت TMDb (production_countries)."""
    names = []
    for c in details.get("production_countries", []) or []:
        code = c.get("iso_3166_1")
        names.append(COUNTRY_FA.get(code, c.get("name")))
    return names
